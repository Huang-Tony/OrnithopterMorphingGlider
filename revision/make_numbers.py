def J(name):
    p = os.path.join(A, name)
    return json.load(open(p)) if os.path.exists(p) else None


def put(key, val, fmt="{:.3f}"):
    if val is None or (isinstance(val, float) and not math.isfinite(val)):
        M[key] = r"\textbf{??}"
    elif isinstance(val, str):
        M[key] = val
    else:
        M[key] = fmt.format(val)


LATERAL_ROWS = [(0.0, 0.0), (0.0, 0.05), (0.0, 0.10), (0.0, 0.15), (0.1, 0.0), (0.1, 0.10), (0.2, 0.05)]


def lateral_macros():
    """Shape dependence of the lateral-directional derivatives (lateral_derivatives.py): macros + table rows."""
    ld = J("lateral_derivatives.json")
    if not ld:
        return
    S = {(round(d["sym_span_m"], 2), round(d["sym_dihedral_m"], 2)): d for d in ld["symmetric"]}
    A = {(d["input"], round(d["amplitude_m"], 2)): d for d in ld["asymmetric"]}
    n, hi = S[(0.0, 0.0)], S[(0.0, 0.15)]
    put("LatClbNeutral", n["Cl_beta_NED"], "{:+.2f}"); put("LatCnbNeutral", 1e3 * n["Cn_beta_NED"], "{:.1f}")
    put("LatLbNeutral", n["L_beta"], "{:.1f}"); put("LatNbNeutral", n["N_beta"], "{:.2f}"); put("LatYbNeutral", n["Y_beta"], "{:.1f}")
    put("LatArchNeutralMm", 1000 * n["arch_height_m"], "{:.0f}")
    put("LatLbRatioTips", n["L_beta"] / hi["L_beta"], "{:.0f}"); put("LatNdsRatioTips", n["N_ds"] / hi["N_ds"], "{:.0f}")
    put("LatClbTips", hi["Cl_beta_NED"], "{:+.3f}")
    d10 = A[("diff_span", 0.1)]
    put("LatNbDyTenNeg", d10["N_beta_neg"], "{:.2f}"); put("LatNbDyTenPos", d10["N_beta_pos"], "{:.2f}")
    put("LatNbDsThirty", min(A[("diff_sweep", 0.3)]["N_beta_neg"], A[("diff_sweep", 0.3)]["N_beta_pos"]), "{:.2f}")
    auth = abs(n["L_dy"]) * C.DY_RANGE[1] + abs(n["L_dd"]) * C.DZ_RANGE[1]      # full differential span + dihedral
    put("LatRollAuth", auth, "{:.2f}"); put("LatBetaSatDeg", math.degrees(auth / abs(n["L_beta"])), "{:.1f}")
    # skid turn: side force needed for r = 0.6 rad/s at V0 vs Y_beta
    P = NOMINAL_PHYS
    beta_skid = P["mass"] * P["V0"] * 0.6 / abs(n["Y_beta"])
    put("LatSkidBetaDeg", math.degrees(beta_skid), "{:.0f}")
    lines = []
    for key in LATERAL_ROWS:
        d = S.get(key)
        if d is None:
            continue
        lines.append(f"{key[0]:.2f} & {key[1]:.2f} & {1000*d['arch_height_m']:.0f} & ${d['Cl_beta_NED']:+.3f}$ & "
                     f"${1e3*d['Cn_beta_NED']:+.1f}$ & ${d['Y_beta']:.1f}$ & ${d['N_ds']:+.2f}$ & {d['L_dy']:.2f}\\\\")
    os.makedirs(os.path.join(RUNS_DIR, "paper_figures"), exist_ok=True)
    with open(os.path.join(RUNS_DIR, "paper_figures", "tab_lateral_rows.tex"), "w") as f:
        f.write("% Auto-generated by revision/make_numbers.py (lateral_derivatives.json)\n" + "\n".join(lines) + "\n")


